"""GS VRAM(4MB) 디스위즐 (PSMCT32 / PSMT8 / PSMT4)."""
import numpy as np
BT32 = [[0,1,4,5,16,17,20,21],[2,3,6,7,18,19,22,23],[8,9,12,13,24,25,28,29],[10,11,14,15,26,27,30,31]]
CT32 = [[0,1,4,5,8,9,12,13],[2,3,6,7,10,11,14,15],[16,17,20,21,24,25,28,29],[18,19,22,23,26,27,30,31],
        [32,33,36,37,40,41,44,45],[34,35,38,39,42,43,46,47],[48,49,52,53,56,57,60,61],[50,51,54,55,58,59,62,63]]
def addr32(bp, bw, w, h):
    y, x = np.mgrid[0:h, 0:w]
    page = (y // 32) * bw + x // 64
    bt = np.array(BT32)[(y % 32) // 8, (x % 64) // 8]
    ct = np.array(CT32)[y % 8, x % 8]
    return bp * 64 + page * 2048 + bt * 64 + ct
def ct32(vram, bp, bw, w, h):
    v = np.frombuffer(vram, np.uint32)
    return v[addr32(bp, bw, w, h) % len(v)]
# PSMT4: 128x128 페이지, 32x16 블록, 블록 내 열 구조
BT4 = [[0,2,8,10,32,34,40,42],[1,3,9,11,33,35,41,43],[4,6,12,14,36,38,44,46],[5,7,13,15,37,39,45,47],
       [16,18,24,26,48,50,56,58],[17,19,25,27,49,51,57,59],[20,22,28,30,52,54,60,62],[21,23,29,31,53,55,61,63]]
def _ct4():
    # GSdx columnTable4 (32x16)
    t = np.zeros((16, 32), int)
    for y in range(16):
        for x in range(32):
            col = y // 4; yy = y % 4
            # 열 내 배치
            even = col % 2 == 0
            xx = x
            # 바이트 내 위치는 GSdx 표를 계산식으로 재현
            t[y, x] = 0
    return t
def t4(vram, bp, bw, w, h):
    """PSMT4 픽셀 인덱스 배열 (GSdx 주소식)."""
    y, x = np.mgrid[0:h, 0:w]
    page = (y // 128) * (bw // 2) + x // 128
    blk = np.array(BT4)[(y % 128) // 16, (x % 128) // 32]
    yb, xb = y % 16, x % 32
    col = yb // 4
    cy = yb % 4
    # 열(32x4) 안의 니블 위치: GSdx columnTable4
    off = _col4(col, cy, xb)
    nib = (bp * 64 + page * 2048 + blk * 64) * 8 + off
    v = np.frombuffer(vram, np.uint8)
    b = v[(nib // 2) % len(v)]
    return np.where(nib % 2, b >> 4, b & 15)
